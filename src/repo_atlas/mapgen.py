"""Generate the root feature map and the matching files for other agent tools."""

from __future__ import annotations

from pathlib import Path

from repo_atlas.naming import first_sentence, humanize, is_generic_symbol
from repo_atlas.protect import Protection
from repo_atlas.scan import RepoIndex
from repo_atlas.signals import FileSignals

START = "<!-- repo-atlas:start -->"
END = "<!-- repo-atlas:end -->"

TOOL_FILES: dict[str, tuple[str, str]] = {
    "agents": (
        "AGENTS.md",
        "# Agent guide\n\n"
        "Add notes outside the repo-atlas markers. "
        "The marked section is rewritten when you run `repo-atlas map`.\n",
    ),
    "claude": (
        "CLAUDE.md",
        "# Claude guide\n\n"
        "Add notes outside the repo-atlas markers. "
        "The marked section is rewritten when you run `repo-atlas map`.\n",
    ),
    "cursor": (
        ".cursor/rules/repo-atlas.mdc",
        "---\n"
        "description: Repository feature map generated by repo-atlas\n"
        "alwaysApply: true\n"
        "---\n\n"
        "# Repository map\n\n"
        "Add notes outside the repo-atlas markers. "
        "The marked section is rewritten when you run `repo-atlas map`.\n",
    ),
    "copilot": (
        ".github/copilot-instructions.md",
        "# Copilot instructions\n\n"
        "Add notes outside the repo-atlas markers. "
        "The marked section is rewritten when you run `repo-atlas map`.\n",
    ),
    "gemini": (
        "GEMINI.md",
        "# Gemini guide\n\n"
        "Add notes outside the repo-atlas markers. "
        "The marked section is rewritten when you run `repo-atlas map`.\n",
    ),
}


def detect_tools(root: Path) -> list[str]:
    """Always include AGENTS.md, plus tools that already have a footprint in the repo."""
    tools = ["agents"]
    if (root / "CLAUDE.md").exists() or (root / ".claude").exists():
        tools.append("claude")
    if (root / ".cursor").exists() or (root / ".cursorrules").exists():
        tools.append("cursor")
    if (root / ".github" / "copilot-instructions.md").exists():
        tools.append("copilot")
    if (root / "GEMINI.md").exists() or (root / ".gemini").exists():
        tools.append("gemini")
    return tools


def parse_tool_list(value: str, root: Path) -> list[str]:
    text = value.strip().lower()
    if text in {"auto", ""}:
        return detect_tools(root)
    if text == "all":
        return list(TOOL_FILES)
    tools = []
    for part in text.split(","):
        name = part.strip().lower()
        if not name:
            continue
        if name not in TOOL_FILES:
            known = ", ".join(TOOL_FILES)
            raise ValueError(f"Unknown map tool {name!r}. Choose from: {known}, auto, all.")
        if name not in tools:
            tools.append(name)
    if not tools:
        return ["agents"]
    return tools


def _primary_name(signals: FileSignals) -> str:
    specific = [
        symbol
        for symbol in signals.symbols
        if not symbol.name.startswith("_") and not is_generic_symbol(symbol.name)
    ]
    exported = [symbol for symbol in specific if symbol.exported]
    pool = exported or specific or signals.symbols
    if pool:
        return pool[0].name
    return signals.stem


def _feature_title(signals: FileSignals) -> str:
    sentence = first_sentence(signals.docstring)
    if sentence:
        return sentence
    return humanize(_primary_name(signals))


def _include_feature(signals: FileSignals, protection: Protection) -> bool:
    if signals.language in {"markdown", "rst", "text"}:
        return False
    reason = protection.reason(signals.path)
    if reason in {"test discovery name", "framework migration"}:
        return False
    if signals.path.name == "__init__.py" and not any(
        not symbol.name.startswith("_") for symbol in signals.symbols
    ):
        return False
    return True


def render_map_body(index: RepoIndex) -> str:
    """Build the managed feature map for the tree as it exists now."""
    protection = Protection(index.root)
    features: list[tuple[str, str]] = []
    for signals in index.files:
        if not _include_feature(signals, protection):
            continue
        title = _feature_title(signals).strip().rstrip(".")
        if not title:
            continue
        features.append((signals.path.as_posix(), title))

    by_dir: dict[str, list[str]] = {}
    for path, title in features:
        parent = Path(path).parent.as_posix()
        by_dir.setdefault(parent, []).append(title)

    lines = [
        "## Feature map",
        "",
        "Generated by repo-atlas from file names, symbols, and docstrings.",
        "",
        "### Directory guide",
        "",
    ]
    if not by_dir:
        lines.append("- No mapped source files.")
    for directory in sorted(by_dir):
        label = "." if directory == "." else directory
        blurbs = [title.rstrip(".") for title in by_dir[directory][:3]]
        lines.append(f"- `{label}/`: " + "; ".join(blurbs) + ".")
    lines.extend(["", "### Features", ""])
    if not features:
        lines.append("- No features were detected.")
    for path, title in features:
        lines.append(f"- `{path}`: {title}.")
    lines.append("")
    return "\n".join(lines)


def upsert_managed(existing: str, body: str) -> str:
    """Insert or replace the managed block and leave every other line alone."""
    block = f"{START}\n{body.rstrip()}\n{END}\n"
    start = existing.find(START)
    end = existing.find(END)
    if start != -1 and end != -1 and end > start:
        close = end + len(END)
        if existing[close : close + 1] == "\n":
            close += 1
        return existing[:start] + block + existing[close:]
    if existing and not existing.endswith("\n"):
        existing += "\n"
    if existing.strip():
        return existing + "\n" + block
    return block


def render_tool_file(existing: str | None, preamble: str, body: str) -> str:
    if existing is None:
        return upsert_managed(preamble if preamble.endswith("\n") else preamble + "\n", body)
    return upsert_managed(existing, body)


def write_maps(root: Path, index: RepoIndex, tools: list[str], *, dry_run: bool) -> list[Path]:
    """Write one managed section per tool. Return the paths written, or that would be written."""
    body = render_map_body(index)
    written: list[Path] = []
    for tool in tools:
        relative, preamble = TOOL_FILES[tool]
        path = root / relative
        existing = path.read_text(encoding="utf-8") if path.is_file() else None
        updated = render_tool_file(existing, preamble, body)
        written.append(path)
        if dry_run:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(updated, encoding="utf-8")
    return written
